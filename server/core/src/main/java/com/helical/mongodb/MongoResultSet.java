    public MongoResultSet(List<ColumnDefinition> columns, List<List<Object>> rows, Statement statement) {
        this.columns = columns;
        this.rows = rows;
        this.statement = statement;
        this.columnNameToIndex = new HashMap<>();
        for (int i = 0; i < columns.size(); i++) {
            columnNameToIndex.put(columns.get(i).getName().toLowerCase(), i + 1);
        }
    }

    public MongoResultSet(List<ColumnDefinition> columns, List<List<Object>> rows) {
        this(columns, rows, null);
    }

    @Override
    public boolean next() throws SQLException {
        checkClosed();
        if (cursor + 1 < rows.size()) {
            cursor++;
            return true;
        }
        cursor = rows.size();
        return false;
    }

